/**
 * Contract for asynchronous plugin key-value storage (`risuai.pluginStorage`).
 * Provides persistent, plugin-scoped storage backed by IndexedDB or file system.
 */
export interface RisuStorage {
  /** Retrieves a parsed value by key, returning `null` if not found */
  getItem<T = unknown>(key: string): Promise<T | null>;
  /** Serializes and stores a value under the given key */
  setItem<T = unknown>(key: string, value: T): Promise<void>;
  /** Removes a stored key-value pair */
  removeItem(key: string): Promise<void>;
  /** Clears all entries stored in this plugin's scope */
  clear(): Promise<void>;
  /** Returns the key name at the specified zero-based index */
  key(index: number): Promise<string | null>;
  /** Returns an array of all stored keys */
  keys(): Promise<string[]>;
  /** Returns the total count of stored entries */
  length(): Promise<number>;
}

/**
 * Contract for asynchronous string-only local storage (`risuai.safeLocalStorage`).
 */
export interface RisuSafeLocalStorage {
  /** Retrieves a raw string value by key, returning `null` if not found */
  getItem(key: string): Promise<string | null>;
  /** Stores a string value under the given key */
  setItem(key: string, value: string): Promise<void>;
  /** Removes a stored key-value pair */
  removeItem(key: string): Promise<void>;
  /** Clears all stored entries */
  clear(): Promise<void>;
  /** Returns the key name at the specified index */
  key(index: number): Promise<string | null>;
  /** Returns the total count of stored entries */
  length(): Promise<number>;
}

/**
 * Contract for local device plugin storage (`risuai.getLocalPluginStorage()`).
 */
export interface RisuLocalPluginStorage {
  /** Retrieves a value by key */
  getItem<T = unknown>(key: string): Promise<T | null>;
  /** Stores a value under the given key */
  setItem<T = unknown>(key: string, value: T): Promise<void>;
  /** Removes a stored key-value pair */
  removeItem(key: string): Promise<void>;
  /** Clears all stored entries */
  clear(): Promise<void>;
  /** Returns an array of all stored keys */
  keys(): Promise<string[]>;
}

