// 7. Global Plugin API Contract (Risuai / risuai)
// ============================================================================

/**
 * Complete contract for the RisuAI Plugin API v3.0 global object (`risuai` / `Risuai`).
 * All methods operate asynchronously over `postMessage` RPC.
 */
export interface RisuaiPluginAPIContract {
  /** API version string (e.g. "3.0") */
  apiVersion: string;
  /** Array of compatible API versions */
  apiVersionCompatibleWith: string[];

  // --- Logging & UI Management ---
  /** Logs a message prefixed with plugin identity */
  log(message: string): Promise<void>;
  /** Displays the plugin's iframe container UI */
  showContainer(mode: RisuContainerMode): Promise<void>;
  /** Hides the plugin's iframe container UI */
  hideContainer(): Promise<void>;

  // --- DOM & Observation ---
  /** Gets the SafeDocument wrapper for the main host window (requires 'mainDom' permission) */
  getRootDocument(): Promise<unknown>;
  /** Creates a safe mutation observer for DOM tracking */
  createMutationObserver(callback: (mutations: unknown) => void): Promise<unknown>;
  /** Unwraps a SafeClassArray or array-like proxy to a native JavaScript Array */
  unwarpSafeArray<T = unknown>(arr: unknown): Promise<T[]>;

  // --- Character & Chat Data Access ---
  /** Retrieves the currently active character object */
  getCharacter(): Promise<RisuCharacter | null>;
  /** Updates the currently active character object */
  setCharacter(character: RisuCharacter | unknown): Promise<void>;
  /** @deprecated Use `getCharacter()` instead */
  getChar(): Promise<unknown>;
  /** @deprecated Use `setCharacter()` instead */
  setChar(character: unknown): Promise<void>;
  /** Retrieves a character by zero-based database index */
  getCharacterFromIndex(index: number): Promise<RisuCharacter | null>;
  /** Saves a character at the specified database index */
  setCharacterToIndex(index: number, character: RisuCharacter | unknown): Promise<void>;
  /** Retrieves a specific chat session for a character */
  getChatFromIndex(characterIndex: number, chatIndex: number): Promise<RisuChat | null>;
  /** Saves a specific chat session for a character */
  setChatToIndex(characterIndex: number, chatIndex: number, chat: RisuChat | unknown): Promise<void>;
  /** Returns the index of the currently active character */
  getCurrentCharacterIndex(): Promise<number>;
  /** Returns the index of the currently active chat session */
  getCurrentChatIndex(): Promise<number>;
  /** Retrieves lorebook entries active in the current session */
  getCurrentLorebookEntries(): Promise<unknown[]>;

  // --- Database Access ---
  /** Queries database properties by key names or `'all'` */
  getDatabase(includeOnly?: RisuDatabaseKey[] | 'all'): Promise<RisuDatabaseSubset | null>;
  /** Lightweight database update */
  setDatabaseLite(db: Partial<RisuDatabaseSubset>): Promise<void>;
  /** Complete database update */
  setDatabase(db: Partial<RisuDatabaseSubset>): Promise<void>;

  // --- Storage Instances ---
  /** Asynchronous key-value plugin storage */
  pluginStorage: RisuStorage;
  /** String-only safe local storage */
  safeLocalStorage: RisuSafeLocalStorage;
  /** Retrieves local device plugin storage instance */
  getLocalPluginStorage(): Promise<RisuLocalPluginStorage>;

  // --- Arguments & Settings ---
  /** Gets configured value for a declared plugin argument */
  getArgument<T = string | number | undefined>(key: string): Promise<T>;
  /** Sets value for a declared plugin argument */
  setArgument(key: string, value: string | number): Promise<void>;
  /** @deprecated Synchronous argument getter (use `getArgument`) */
  getArg(key: string): unknown;
  /** @deprecated Synchronous argument setter (use `setArgument`) */
  setArg(key: string, value: string | number): void;

  // --- UI Registration ---
  /** Registers a settings menu item with custom click handler */
  registerSetting(
    name: string,
    callback: () => void | Promise<void>,
    icon?: string,
    iconType?: RisuIconType,
    id?: string
  ): Promise<RisuUIPartResponse>;
  /** Registers a button in RisuAI toolbars */
  registerButton(
    arg: Record<string, unknown>,
    callback: () => void | Promise<void>
  ): Promise<RisuUIPartResponse>;
  /** Unregisters a previously registered UI part by ID */
  unregisterUIPart(id: string): Promise<void>;

  // --- Theming & Styling ---
  /** Switches active color scheme by preset name */
  changeColorScheme(name: string): Promise<void>;
  /** Applies custom color scheme */
  setColorScheme(scheme: Partial<RisuColorScheme>): Promise<void>;
  /** Gets currently active color scheme */
  getColorScheme(): Promise<{ name: string; scheme: RisuColorScheme }>;
  /** Switches active text theme */
  changeTextTheme(name: string): Promise<void>;
  /** Applies custom text styling theme */
  setCustomTextTheme(theme: Partial<RisuCustomTextTheme>): Promise<void>;
  /** Gets currently active text theme */
  getTextTheme(): Promise<{ name: string; customTheme: RisuCustomTextTheme }>;

  // --- Network & Native APIs ---
  /** Executes CORS-bypassing HTTP request using native host environment */
  nativeFetch(url: string, options?: RisuNativeFetchOptions): Promise<Response>;
  /** Saves secret header configuration */
  saveSecretHeader(key: string, prefix: string, value: string | string[]): Promise<void>;

  // --- Security & Permissions ---
  /** Requests user permission for a sensitive operation scope */
  requestPluginPermission(permission: RisuPluginPermission): Promise<boolean>;

  // --- Assets & Image Decoding ---
  /** Reads raw binary bytes for an asset identifier (e.g. "assets/...") */
  readImage(assetId: string): Promise<Uint8Array | ArrayBuffer>;
  /** Reads raw asset data */
  readAsset?(assetId: string): Promise<Uint8Array | ArrayBuffer>;
  /** Saves raw binary asset data, returning new asset identifier */
  saveAsset?(data: Uint8Array | ArrayBuffer, filename?: string): Promise<string>;

  // --- Interceptors & Lifecycle ---
  /** Registers a replacer hook for prompt/response manipulation */
  registerReplacer?(
    type: RisuReplacerType,
    handler: (data: unknown) => unknown | Promise<unknown>
  ): Promise<void>;
  /** Registers a TTS preprocessor hook */
  addTTSPreprocessor?(
    fn: (ctx: RisuBeforeTTSContext) => RisuBeforeTTSResult | Promise<RisuBeforeTTSResult>
  ): Promise<void>;
  /** Registers a TTS postprocessor hook */
  addTTSPostprocessor?(
    fn: (ctx: RisuAfterTTSContext) => RisuAfterTTSResult | Promise<RisuAfterTTSResult>
  ): Promise<void>;
  /** Registers plugin cleanup handler fired when plugin is disabled or reloaded */
  onUnload(callback: () => void): void;
  /** Host runtime environment info query */
  getRuntimeInfo?(): Promise<RisuRuntimeInfo>;
}

