/**
 * Entity type indicating single character vs multi-character group chat.
 */
export type RisuCharacterType = 'character' | 'group' | (string & {});

/**
 * 3-tuple asset definition: `[assetId, filename, mimeType]`.
 * Used for additional assets attached to character cards and modules.
 */
export type RisuAssetTuple = [id: string, name: string, type: string];

/**
 * 2-tuple emotion portrait definition: `[emotionKey, assetId]`.
 * Used to map emotional expressions to avatar image asset IDs.
 */
export type RisuEmotionTuple = [emotion: string, assetId: string];

/**
 * RisuAI Character entity representing single character data, definitions, and chat sessions.
 * Based on RisuAI `character` interface in `database.svelte.ts`.
 */
export interface RisuCharacter {
  /** Character display name */
  name: string;
  /** Primary avatar asset identifier (e.g. "assets/..."). Note: Replaces legacy `avatar` field */
  image?: string;
  /** Unique character identifier */
  chaId: string;
  /** List of chat conversation sessions for this character */
  chats: RisuChat[];
  /** Currently active chat session index (0-indexed) */
  chatPage: number;
  /** Chat folder organization list */
  chatFolders?: RisuChatFolder[];
  /** Entity discriminator ('character' or 'group') */
  type?: RisuCharacterType;
  /** Primary greeting message */
  firstMessage?: string;
  /** List of alternative opening greetings */
  alternateGreetings?: string[];
  /** Selected alternate greeting index */
  firstMsgIndex?: number;
  /** Additional asset files attached to this character card [id, filename, mimeType] */
  additionalAssets?: RisuAssetTuple[];
  /** Emotion expression image mappings [emotionKey, assetId] */
  emotionImages?: RisuEmotionTuple[];
  /** Whether character displays in full-body/large portrait mode */
  largePortrait?: boolean;
  /** Display nickname override */
  nickname?: string;
  /** Whether the avatar icon is hidden in chat UI */
  hideChatIcon?: boolean;
  /** Character description prompt */
  description?: string;
  /** Character personality definition prompt */
  personality?: string;
  /** Scenario / situation setting prompt */
  scenario?: string;
  /** Example dialogue lines (<START>...) */
  mesExamples?: string;
  /** Creator notes and usage guidelines */
  creatorNotes?: string;
  /** Character-level system prompt override */
  systemPrompt?: string;
  /** Post-history instructions prompt */
  postHistoryInstructions?: string;
  /** Categorization tags */
  tags?: string[];
  /** Creator / author name */
  creator?: string;
  /** Character specification / version string */
  characterVersion?: string;
  /** Extensible index signature for forward compatibility */
  [key: string]: unknown;
}

/**
 * RisuAI Group Chat entity combining multiple character definitions into a shared chat room.
 */
export interface RisuGroupChat extends RisuCharacter {
  /** Entity discriminator strictly typed to 'group' */
  type: 'group';
  /** Array of participating character `chaId` identifiers */
  characters: string[];
  /** Talk frequency weighting / turn counts per character */
  characterTalks: number[];
  /** Active participating state flag per character */
  characterActive: boolean[];
}

