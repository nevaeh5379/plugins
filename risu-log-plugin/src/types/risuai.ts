// 1. Message & Chat Data Models
// ============================================================================

/**
 * Valid role identifiers for chat messages in RisuAI.
 * - `'user'`: Message sent by the human user or active persona.
 * - `'char'`: Message generated by the AI character.
 */
export type RisuMessageRole = 'user' | 'char' | (string & {});

/**
 * Context inclusion state for an individual message:
 * - `false`: Message is included in LLM context prompt (default active state).
 * - `true`: Message is individually excluded from LLM context prompt.
 * - `'allBefore'`: All messages prior to this message (inclusive) are excluded from context.
 */
export type RisuMessageDisabled = boolean | 'allBefore';

/**
 * Single message entry within a RisuAI chat session.
 */
export interface RisuMessage {
  /** Role identifier designating the message sender ('user' | 'char') */
  role: RisuMessageRole;
  /** Raw textual content of the message including markdown, dialogue formatting, and HTML tags */
  data: string;
  /** Spoken dialogue extracted or designated for TTS (Text-to-Speech) synthesis */
  saying?: string;
  /** Unique message identifier (UUID or session-local ID) */
  chatId?: string;
  /** Creation Unix timestamp in milliseconds */
  time?: number;
  /** Speaker display name override (used in multi-character/group chats) */
  name?: string;
  /** Flag indicating whether the message originates from an auxiliary user persona */
  otherUser?: boolean;
  /** Exclusion flag for LLM prompt context construction */
  disabled?: RisuMessageDisabled;
  /** Whether this item is an author's comment/note rather than an active dialogue message */
  isComment?: boolean;
  /** Emotion asset key associated with this message turn (e.g. "happy", "angry") */
  emotion?: string;
  /** Audio asset URL or identifier associated with voice output */
  audio?: string;
  /** Extensible index signature for forward compatibility */
  [key: string]: unknown;
}

/**
 * Folder categorization for organizing character chat sessions in the sidebar UI.
 */
export interface RisuChatFolder {
  /** Unique folder identifier */
  id: string;
  /** Optional human-readable display name of the folder */
  name?: string;
  /** Optional hex or CSS color code for folder badge styling */
  color?: string;
  /** Whether the folder is collapsed in the chat selection sidebar */
  folded: boolean;
  /** Extensible index signature for forward compatibility */
  [key: string]: unknown;
}

/**
 * Individual chat conversation session with a character or group.
 */
export interface RisuChat {
  /** Ordered array of messages comprising the chat history */
  message: RisuMessage[];
  /** Scenario / author's note specific to this chat session */
  note: string;
  /** User-assigned title of the chat session */
  name: string;
  /** Unique session identifier */
  id?: string;
  /** ID of the user persona bound to this chat session */
  bindedPersona?: string;
  /** Selected first message / greeting alternative index */
  fmIndex?: number;
  /** Containing folder identifier matching `RisuChatFolder.id` */
  folderId?: string;
  /** Last activity Unix timestamp in milliseconds */
  lastDate?: number;
  /** Array of bookmarked message IDs (`chatId`) */
  bookmarks?: string[];
  /** Mapping of message `chatId` to user-defined bookmark label */
  bookmarkNames?: Record<string, string>;
  /** Chat-local lorebook entries */
  localLore?: unknown[];
  /** Stable Diffusion generation prompt metadata */
  sdData?: string;
  /** SupaMemory summary and state data */
  supaMemoryData?: string;
  /** Hypa memory V2 embedding vector data */
  hypaV2Data?: unknown;
  /** Hypa memory V3 embedding vector data */
  hypaV3Data?: unknown;
  /** Most recent summarized memory text */
  lastMemory?: string;
  /** AI-generated follow-up message suggestions */
  suggestMessages?: string[];
  /** Whether chat response is currently streaming */
  isStreaming?: boolean;
  /** Custom script runtime state */
  scriptstate?: unknown;
  /** List of enabled module IDs active in this chat */
  modules?: string[];
  /** Extensible index signature for forward compatibility */
  [key: string]: unknown;
}

